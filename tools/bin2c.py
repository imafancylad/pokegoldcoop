#!/usr/bin/env python3
"""Convert the generated .bin files into C headers that can be embedded in the ELF."""
import sys
from pathlib import Path

ASSETS = [
    ("bg_tiles_palettes.bin", "bg_tiles_palettes"),
    ("johto_tiles.rgba",      "johto_tiles"),
    ("johto_blocks.bin",      "johto_blocks"),
    ("newbark_map.bin",       "newbark_map"),
]

GEN_DIR = Path("data/generated")
OUT_H   = Path("src/assets_data.h")

def emit_bytes(f, data):
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        f.write("    " + ",".join(f"0x{b:02X}" for b in chunk) + ",\n")

def main():
    with open(OUT_H, "w") as f:
        f.write("/* AUTO-GENERATED by tools/bin2c.py — do not edit by hand */\n")
        f.write("#ifndef ASSETS_DATA_H\n#define ASSETS_DATA_H\n\n")
        f.write("#include <stdint.h>\n\n")

        for fname, sym in ASSETS:
            p = GEN_DIR / fname
            if not p.exists():
                sys.exit(f"Missing {p}, run 'make assets' first")
            data = p.read_bytes()
            size = len(data)
            f.write(f"/* {fname} — {size} bytes */\n")
            f.write(f"const uint8_t {sym}[{size}] __attribute__((aligned(16))) = {{\n")
            emit_bytes(f, data)
            f.write("};\n\n")

        f.write("#endif /* ASSETS_DATA_H */\n")

    print(f"OK: {OUT_H} ({OUT_H.stat().st_size} bytes)")

if __name__ == "__main__":
    main()